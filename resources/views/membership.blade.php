Halaman untuk user melakukan transaksi membership, isinya:
1. pilihan waktu: 1 bulan, 3 bulan, 6 bulan, dan 1 tahun.
2. dibawahnya ada pilihan pt, tiap-tiap card berisi foto PT dan deskripsi diri pt.
3. apabila user memilih pt, dibawah daftar pt akan muncul daftar jadwal yang tersedia.
    berisi hari, jam, dan rincian latihan. Contoh: Senin, 10.00 - 12.00, Upper Body.
4. dipaling bawah akan menunjukkan rincian biaya dan toalnya, serta sebuah tombol "bayar".